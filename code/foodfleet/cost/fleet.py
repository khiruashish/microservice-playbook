#!/usr/bin/env python3
"""Writes the container fleet as chapter 70's Fleet reads it (service, team, kind, replicas, cpu, memGiB), from the
values files deploy/generate.py wrote and the chart's defaults: once at the HPAs' minimums, once at their maximums."""
import glob
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULTS = yaml.safe_load(open(os.path.join(HERE, "..", "deploy", "foodfleet-service", "values.yaml")))


def cpu(v):
    v = str(v)
    return int(v[:-1]) / 1000 if v.endswith("m") else float(v)


def mem(v):
    v = str(v)
    return int(v[:-2]) / 1024 if v.endswith("Mi") else float(v[:-2])


for bound in ("minReplicas", "maxReplicas"):
    rows = ["# generated by fleet.py from deploy/values (%s)" % bound]
    for f in sorted(glob.glob(os.path.join(HERE, "..", "deploy", "values", "*.yaml"))):
        v = yaml.safe_load(open(f))
        r = {**DEFAULTS["resources"], **v.get("resources", {})}
        rows.append("\t".join([v["name"], v["team"], "api", str(v["autoscaling"][bound]), "%g" % cpu(r["cpu"]), "%g" % mem(r["memory"])]))
    with open(os.path.join(HERE, "fleet-%s.tsv" % bound[:3]), "w") as out:
        out.write("\n".join(rows) + "\n")
