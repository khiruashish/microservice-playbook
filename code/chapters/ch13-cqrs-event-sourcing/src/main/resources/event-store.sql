-- One table, append-only. (stream_id, stream_version) unique = optimistic concurrency;
-- global_position orders all events for projections.
create table if not exists event_store (
    global_position bigint generated by default as identity primary key,
    stream_id       varchar(100) not null,
    stream_version  bigint       not null,
    event_type      varchar(100) not null,
    schema_version  int          not null,
    payload         varchar(4000) not null,
    recorded_at     timestamp    not null,
    constraint event_store_stream_version unique (stream_id, stream_version)
);
