#!/usr/bin/env python3
"""Handbook generator: keeps docs/, mkdocs.yml nav and the roadmap in sync with
tools/master-plan.yml.

Usage (from the handbook root):
    python3 tools/handbook.py            # create missing stubs, rebuild nav + roadmap
    python3 tools/handbook.py --check    # exit 1 if nav/stubs are out of date (CI)

A page counts as "done" when its front matter has `progress: done`.
Stubs are written with `progress: planned` and are never overwritten.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
PLAN = ROOT / "tools" / "master-plan.yml"
MKDOCS = ROOT / "mkdocs.yml"
ROADMAP = DOCS / "appendix" / "roadmap.md"

NAV_START = "# >>> nav (generated by tools/handbook.py - do not edit by hand)"
NAV_END = "# <<< nav"

BAND_LABEL = {
    1: ("badge-l1", "L1 · Foundation"),
    2: ("badge-l2", "L2 · Practitioner"),
    3: ("badge-l3", "L3 · Senior/Lead"),
    4: ("badge-l4", "L4 · Architect"),
}
BAND_EMOJI = {1: "🟢", 2: "🔵", 3: "🟣", 4: "🔴"}


def badges_html(bands: list[int]) -> str:
    spans = "".join(
        f'<span class="badge {BAND_LABEL[b][0]}">{BAND_LABEL[b][1]}</span>' for b in bands
    )
    return f'<div class="badges" markdown>{spans}</div>'


def iter_pages(section: dict):
    """Yield (group_name | None, page) for a section with or without groups."""
    if "groups" in section:
        for group in section["groups"]:
            for page in group["pages"]:
                yield group["name"], page
    else:
        for page in section["pages"]:
            yield None, page


def page_path(section: dict, page: dict) -> Path:
    return DOCS / section["dir"] / page["file"]


def read_progress(path: Path) -> str:
    if not path.exists():
        return "missing"
    text = path.read_text(encoding="utf-8")
    match = re.search(r"^progress:\s*(\w+)", text, re.MULTILINE)
    return match.group(1) if match else "done"


def stub_content(section: dict, page: dict) -> str:
    return f"""---
title: "{page['title']}"
description: "{page['scope']}"
progress: planned
---

# {page['title']}

{badges_html(page['bands'])}

!!! abstract "Planned page · `{page['id']}`"
    **Scope:** {page['scope']}.

    This page is in the generation queue. See the [Handbook Roadmap]({rel_link(section, 'appendix/roadmap.md')}) for progress.
"""


def rel_link(section: dict, target: str) -> str:
    depth = len(Path(section["dir"]).parts)
    return "../" * depth + target


def build_nav(plan: dict) -> str:
    lines = ["nav:", "  - Home: index.md"]
    for section in plan["sections"]:
        lines.append(f"  - {yaml_str(section['tab'])}:")
        if "groups" in section:
            for group in section["groups"]:
                lines.append(f"      - {yaml_str(group['name'])}:")
                for page in group["pages"]:
                    lines.append(
                        f"          - {yaml_str(page['title'])}: {section['dir']}/{page['file']}"
                    )
        else:
            for page in section["pages"]:
                if page["file"] == "index.md":
                    lines.append(f"      - {section['dir']}/index.md")
                else:
                    lines.append(
                        f"      - {yaml_str(page['title'])}: {section['dir']}/{page['file']}"
                    )
    return "\n".join(lines)


def yaml_str(value: str) -> str:
    return '"' + value.replace('"', '\\"') + '"'


def build_roadmap(plan: dict) -> str:
    total = done = 0
    body: list[str] = []
    for section in plan["sections"]:
        body.append(f"\n## {section['tab']}\n")
        body.append("| ID | Page | Bands | Status |")
        body.append("|---|---|---|---|")
        for _, page in iter_pages(section):
            if page["id"] == "ap-01":
                continue
            total += 1
            status = read_progress(page_path(section, page))
            is_done = status == "done"
            done += is_done
            link = f"../{section['dir']}/{page['file']}"
            bands = " ".join(BAND_EMOJI[b] for b in page["bands"])
            mark = "✅ Done" if is_done else "⏳ Planned"
            body.append(f"| `{page['id']}` | [{page['title']}]({link}) | {bands} | {mark} |")
    pct = round(100 * done / total) if total else 0
    header = f"""---
title: "Handbook Roadmap & Progress"
description: "Generated progress tracker for every page in the handbook"
---

# Handbook Roadmap & Progress

!!! info "Generated file"
    This page is generated by `tools/handbook.py` from `tools/master-plan.yml`. Do not edit by hand.

**Progress: {done} / {total} pages complete ({pct}%)**

<div class="progress-bar"><span style="width: {pct}%"></span></div>

Legend: 🟢 L1 Foundation · 🔵 L2 Practitioner · 🟣 L3 Senior/Lead · 🔴 L4 Architect/Principal
"""
    return header + "\n".join(body) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    plan = yaml.safe_load(PLAN.read_text(encoding="utf-8"))

    ids = [p["id"] for s in plan["sections"] for _, p in iter_pages(s)]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        print(f"Duplicate ids in master plan: {sorted(dupes)}")
        return 1

    created = []
    for section in plan["sections"]:
        for _, page in iter_pages(section):
            path = page_path(section, page)
            if not path.exists() and page["id"] != "ap-01":
                created.append(path)
                if not check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(stub_content(section, page), encoding="utf-8")

    mk = MKDOCS.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(NAV_START) + r".*?" + re.escape(NAV_END), re.DOTALL)
    if not pattern.search(mk):
        print("mkdocs.yml is missing the nav markers")
        return 1
    new_mk = pattern.sub(lambda _: f"{NAV_START}\n{build_nav(plan)}\n{NAV_END}", mk)

    roadmap = build_roadmap(plan)

    if check:
        stale = created or new_mk != mk or (
            not ROADMAP.exists() or ROADMAP.read_text(encoding="utf-8") != roadmap
        )
        print("out of date" if stale else "up to date")
        return 1 if stale else 0

    MKDOCS.write_text(new_mk, encoding="utf-8")
    ROADMAP.parent.mkdir(parents=True, exist_ok=True)
    ROADMAP.write_text(roadmap, encoding="utf-8")
    print(f"stubs created: {len(created)} · pages in plan: {len(ids)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
