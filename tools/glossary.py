#!/usr/bin/env python3
"""Builds docs/getting-started/glossary.md from the definition lists in every finished chapter.

Each term keeps the definition from the first chapter (by number) that defines it, with links to every chapter that
does. Relative links inside definitions are rewritten to work from getting-started/. Run from the repository root:
    python3 tools/glossary.py
"""
import glob
import os
import re

DOCS = "docs"
OUT = os.path.join(DOCS, "getting-started", "glossary.md")
TERM = re.compile(r"\n\n([A-Za-z0-9][^\n]{0,90})\n(:   [^\n]*(?:\n(?:    [^\n]*|))*?)(?=\n\n(?! {4})|\n\n {0,3}\S|\Z)")


def chapter_number(path):
    m = re.search(r"/ch(\d+)-", path)
    return int(m.group(1)) if m else 999


def title(text):
    m = re.search(r'^title: "(.*)"', text, re.M)
    return m.group(1) if m else ""


def relink(text, chapter_dir):
    def fix(m):
        target = m.group(2)
        if re.match(r"(https?:|mailto:|#|\.\./)", target):
            return m.group(0)
        return "%s../%s/%s)" % (m.group(1), chapter_dir, target)
    return re.sub(r"(\]\()([^)\s]+)\)", lambda m: fix(m), text)


def main():
    terms = {}
    for path in sorted(glob.glob(os.path.join(DOCS, "*", "ch[0-9][0-9]-*.md")), key=chapter_number):
        text = open(path, encoding="utf-8").read()
        if "progress: done" not in text:
            continue
        section = text.split("## 2 ·", 1)[-1].split("\n## 3 ·", 1)[0] if "## 2 ·" in text else ""
        chapter_dir = os.path.basename(os.path.dirname(path))
        link = "../%s/%s" % (chapter_dir, os.path.basename(path))
        for m in TERM.finditer("\n\n" + section):
            term = m.group(1).strip()
            if term.startswith(("!!!", "|", "-", "#", "<", "`")) or len(term.split()) > 9:
                continue
            body = m.group(2).rstrip()
            key = term.lower()
            entry = terms.setdefault(key, {"term": term, "body": relink(body, chapter_dir), "chapters": []})
            entry["chapters"].append((chapter_number(path), title(text), link))
    by_letter = {}
    for key in sorted(terms, key=lambda k: re.sub(r"[^a-z0-9]", "", k)):
        letter = re.sub(r"[^a-z0-9]", "", key)[:1].upper()
        by_letter.setdefault(letter if letter.isalpha() else "0–9", []).append(terms[key])
    lines = [
        "---",
        'title: "Glossary"',
        'description: "%d terms defined across the handbook\'s chapters, each with its definition and links to every chapter that defines it."' % len(terms),
        "progress: done",
        "---",
        "",
        "# Glossary",
        "",
        '<div class="badges" markdown><span class="badge badge-l1">L1 · Foundation</span><span class="badge badge-l2">L2 · Practitioner</span>'
        '<span class="badge badge-l3">L3 · Senior/Lead</span><span class="badge badge-l4">L4 · Architect</span></div>',
        "",
        "Every term below is defined in section 2 of at least one chapter. The definition shown is the first chapter's;",
        "the links lead to every chapter that defines it, where it's explained with diagrams, code and measurements.",
        "This page is generated by `tools/glossary.py` from the chapters, so it changes when they do.",
        "",
        "**%d terms** from **%d chapters.** Jump to: %s" % (
            len(terms), len({c[2] for t in terms.values() for c in t["chapters"]}),
            " · ".join("[%s](#%s)" % (l, "09" if l == "0–9" else l.lower()) for l in by_letter)),
        "",
    ]
    for letter, entries in by_letter.items():
        lines += ["## %s" % letter, ""]
        for e in entries:
            refs = ", ".join("[%d](%s)" % (n, link) for n, _, link in sorted(set(e["chapters"])))
            lines += [e["term"], e["body"], "", "    *Chapter%s %s*" % ("s" if len(set(e["chapters"])) > 1 else "", refs), ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print("%s: %d terms" % (OUT, len(terms)))


if __name__ == "__main__":
    main()
